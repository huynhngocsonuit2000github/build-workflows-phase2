// Expands the compact phase files into the study plan's plan-data.js.
const fs = require('fs');
const path = require('path');

const L = (p) => (Array.isArray(p) ? { vi: p[0], en: p[1] } : p);
const expandItem = (x) => {
  const o = { id: x.id, title: L(x.t) };
  if (x.kind) o.kind = x.kind;
  if (x.note) o.note = L(x.note);
  o.time = { vi: x.h + ' giờ', en: x.h + ' h' };
  o.goal = L(x.goal);
  o.learn = (x.learn || []).map(L);
  o.ai = (x.ai || []).map(([tool, why, prompt]) => ({ tool, why: L(why), prompt: L(prompt) }));
  o.resources = (x.res || []).map(([label, url]) => ({ label, url }));
  o.practice = (x.pr || []).map(L);
  o.done = (x.done || []).map(L);
  return o;
};
const expandPhase = (p) => ({
  id: p.id, code: p.code, title: L(p.title), goal: L(p.goal), desc: L(p.desc), color: p.color,
  milestones: p.milestones.map((m) => {
    const t = L(m.title);
    const step = (m.id.match(/^s([0-9]+)$/) || [])[1]; // roadmap step number shown in the title
    return { id: m.id, title: step ? { vi: 'Bước ' + step + ' · ' + t.vi, en: 'Step ' + step + ' · ' + t.en } : t, items: m.items.map(expandItem) };
  }),
});

const meta = require('./meta.js');
const raw = ['p0.js', 'p1.js', 'p2.js', 'p3.js'].map((f) => require('./' + f));
// AI engineering + architecture additions (new ids only)
const extra = require('./extra.js');
for (const e of extra.items) {
  const ms = raw.find((p) => p.id === e.phase).milestones.find((m) => m.id === e.ms);
  const at = e.before ? ms.items.findIndex((x) => x.id === e.before) : ms.items.length;
  ms.items.splice(at, 0, e.item);
}
for (const e of extra.milestones) {
  const p = raw.find((x) => x.id === e.phase);
  p.milestones.splice(p.milestones.findIndex((m) => m.id === e.after) + 1, 0, e.ms);
}
// round 2: closer to real projects
const extra2 = require('./extra2.js');
const allItems = () => raw.flatMap((p) => p.milestones.flatMap((m) => m.items.map((x, i) => ({ m, i, x }))));
for (const [id, item] of Object.entries(extra2.replace)) {
  const hit = allItems().find((r) => r.x.id === id);
  hit.m.items[hit.i] = item;
}
for (const e of extra2.items) {
  const ms = raw.find((p) => p.id === e.phase).milestones.find((m) => m.id === e.ms);
  const at = e.before ? ms.items.findIndex((x) => x.id === e.before) : ms.items.length;
  ms.items.splice(at, 0, e.item);
}
for (const [id, tools] of Object.entries(extra2.adr)) {
  const hit = allItems().find((r) => r.x.id === id);
  hit.x.done.push([
    'Viết ADR "build hay mua": so phần tự viết với ' + tools + ', ghi khi nào nên chuyển sang công cụ có sẵn',
    'Write a "build vs buy" ADR: compare your version with ' + tools + ', and note when to switch to a ready-made tool',
  ]);
}
const ids = raw.flatMap((p) => p.milestones.flatMap((m) => m.items.map((x) => x.id)));
if (new Set(ids).size !== ids.length) throw new Error('duplicate item id');
const phases = raw.map(expandPhase);
const plan = { meta, phases };
const out = process.argv[2];
fs.writeFileSync(out, '// GENERATED by _src/build.js from _src/*.js. Do not edit by hand: edit _src, then rebuild. Keep item ids stable.\nwindow.PLAN = ' + JSON.stringify(plan, null, 2) + ';\n');
const n = phases.reduce((a, p) => a + p.milestones.reduce((b, m) => b + m.items.length, 0), 0);
console.log('wrote', out, phases.length, 'phases', phases.reduce((a, p) => a + p.milestones.length, 0), 'milestones', n, 'items');
